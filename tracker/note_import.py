from __future__ import annotations

import re
from pathlib import Path

from django.db import transaction

from .models import KnowledgeNote, KnowledgeSection, Profile


def clean_transcript_text(raw_text: str) -> str:
    """Remove speaker markers and collapse noisy blank lines."""
    cleaned_lines: list[str] = []
    for line in raw_text.splitlines():
        stripped = line.strip()
        if not stripped:
            cleaned_lines.append("")
            continue
        if stripped.startswith("Speaker "):
            continue
        if stripped.startswith("> Generated by "):
            continue
        cleaned_lines.append(stripped)
    cleaned = "\n".join(cleaned_lines)
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)
    return cleaned.strip()


def title_from_source_path(source_path: str) -> str:
    stem = Path(source_path).stem
    stem = stem.replace("_逐字稿", "")
    return stem.strip() or "Imported transcript note"


