@transaction.atomic
def import_transcript_note(source_path: str, raw_text: str, title: str | None = None) -> KnowledgeNote:
    profile = Profile.objects.order_by("id").first()
    if profile is None:
        profile = Profile.objects.create(display_name="Athlete", height_cm=175.0)

    resolved_title = title or title_from_source_path(source_path)
    payload = build_note_payload(resolved_title, source_path, raw_text)
    sections = payload.pop("sections")

    note, _ = KnowledgeNote.objects.update_or_create(
        profile=profile,
        title=payload["title"],
        defaults=payload,
    )
    note.sections.all().delete()
    KnowledgeSection.objects.bulk_create(
        [KnowledgeSection(note=note, **section) for section in sections]
    )
    return note
